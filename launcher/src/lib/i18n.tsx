export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const dict = lang === 'en' ? en : tr
  let str = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v))
    }
  }
  return str
}

export function errorKey(code: string | null | undefined, fallback: TKey = 'errors.auth.generic'): TKey {
  if (!code) return fallback
  const key = `errors.${code.replace(/\//g, '.')}` as TKey
  return key in tr ? key : fallback
}

const STORAGE_KEY = 'dli_lang'

function loadLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'en' || stored === 'tr') return stored
  } catch {}
  return 'tr'
}

interface I18nContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: TKey, vars?: Record<string, string | number>) => string
  tErr: (code: string | null | undefined, fallback?: TKey) => string
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'tr',
  setLang: () => {},
  t: (key) => key,
  tErr: () => '',
})

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(loadLang)

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch {}
  }, [lang])

  const setLang = useCallback((l: Lang) => setLangState(l), [])

  const value = useMemo<I18nContextValue>(() => {
    return {
      lang,
      setLang,
      t: (key, vars) => translate(lang, key, vars),
      tErr: (code, fallback) => translate(lang, errorKey(code, fallback), { code: code || '' }),
    }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
